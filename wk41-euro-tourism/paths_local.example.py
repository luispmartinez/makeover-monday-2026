"""
Machine-specific paths. NOT generated by any build script -- edit once and every
pipeline script picks it up. Regenerated build_*.py files import from here, so
these paths survive being handed a revised script.
"""
from pathlib import Path

# Scripts and source file. This lives in iCloud-synced Documents, which is fine
# for inputs you open by hand.
RAW = Path(__file__).parent

# Tableau extracts. MUST be local disk. iCloud evicts idle files and leaves
# zero-byte placeholders that Tableau refreshes into blank extracts without error.
OUT = Path.home() / "TableauData" / "Euro Tourism"

SOURCE_FILE = RAW / "drop" / "Tourism_2025.xlsx"
FONTS_DIR = RAW / "fonts"

_CLOUD = ("icloud", "com~apple~clouddocs", "dropbox", "onedrive", "google drive")


def ensure():
    """Create the output dir. Refuse to write extracts anywhere cloud-synced."""
    low = str(OUT.resolve()).lower()
    for token in _CLOUD:
        if token in low:
            raise RuntimeError(
                f"OUT resolves to a cloud-synced path ({OUT}).\n"
                "Move it to local disk before running."
            )
    OUT.mkdir(parents=True, exist_ok=True)
    for f in [SOURCE_FILE]:
        if not f.exists():
            raise FileNotFoundError(f"source file not found: {f}")
    return OUT


def write_atomic(df, name, **kwargs):
    """Write via temp-file rename so a crashed run never leaves a partial file
    that Tableau will happily refresh from."""
    final = OUT / name
    tmp = final.with_suffix(final.suffix + ".tmp")
    df.to_csv(tmp, index=False, **kwargs)
    tmp.replace(final)
    return final
